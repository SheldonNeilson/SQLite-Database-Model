package za.co.neilson.sqlite.orm;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import java.sql.SQLException;
import java.util.Calendar;
import java.util.Date;

import org.junit.Before;
import org.junit.Test;

import za.co.neilson.sqlite.orm.annotations.ForeignKey;
import za.co.neilson.sqlite.orm.annotations.Nullable;
import za.co.neilson.sqlite.orm.annotations.PrimaryKey;
import za.co.neilson.sqlite.orm.annotations.Unique;

/** The CREATE TABLE / ALTER TABLE / CREATE INDEX statements generated by {@link ObjectModel#onCreateTable()}. */
public class ObjectModelCreateTableTest {

    enum Mode {A, B}

    static class DdlTypes {
        @PrimaryKey(autoIncrement = true)
        long id;
        String s;
        boolean prim;
        Boolean boxed;
        byte by;
        short sh;
        int i;
        long l;
        float f;
        double d;
        Date date;
        Calendar calendar;
        byte[] blob;
    }

    static class DdlConstraints {
        @PrimaryKey
        String code;
        @Nullable(false)
        String required;
        @Unique
        String email;
        @Unique
        @Nullable(false)
        String strict;
    }

    static class DdlComposite {
        @PrimaryKey
        int a;
        @PrimaryKey
        String b;
        String payload;
    }

    static class DdlParent {
        @PrimaryKey(autoIncrement = true)
        long id;
    }

    static class DdlChild {
        @ForeignKey(table = "DdlParent", column = "id")
        @Nullable(false)
        long parentId;
        @PrimaryKey(autoIncrement = true)
        long id;
        String note;
    }

    static class DdlTree {
        @PrimaryKey(autoIncrement = true)
        long id;
        String label;
        @ForeignKey(table = "DdlTree", column = "id")
        Long parentId;
    }

    static class DdlEmpty {
        transient int skipped;
    }

    private FakeDriver driver;

    @Before
    public void setUp() {
        OrmTestState.reset();
        driver = new FakeDriver();
    }

    private static String normalise(String sql) {
        return sql.replaceAll("\\s+", " ").trim();
    }

    private String createSql(Class<?> entity) throws Exception {
        FakeDatabaseModel db = register(entity);
        db.getObjectModels().get(entity).onCreateTable();
        return normalise(driver.executed.get(0));
    }

    private FakeDatabaseModel register(final Class<?> entity) throws Exception {
        return FakeDatabaseModel.createExisting(driver, 1, (db, models) -> {
            if (entity == DdlTypes.class) models.put(entity, new FakeObjectModel<DdlTypes>(db) {});
            else if (entity == DdlConstraints.class) models.put(entity, new FakeObjectModel<DdlConstraints>(db) {});
            else if (entity == DdlComposite.class) models.put(entity, new FakeObjectModel<DdlComposite>(db) {});
            else if (entity == DdlEmpty.class) models.put(entity, new FakeObjectModel<DdlEmpty>(db) {});
            else if (entity == DdlTree.class) models.put(entity, new FakeObjectModel<DdlTree>(db) {});
            else if (entity == DdlChild.class) {
                models.put(DdlParent.class, new FakeObjectModel<DdlParent>(db) {});
                models.put(DdlChild.class, new FakeObjectModel<DdlChild>(db) {});
            } else throw new IllegalArgumentException(entity.getName());
        });
    }

    @Test
    public void everySupportedTypeMapsToItsSqliteColumnType() throws Exception {
        assertEquals("CREATE TABLE IF NOT EXISTS \"DdlTypes\" ( "
                + "\"id\" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, "
                + "\"s\" TEXT, "
                + "\"prim\" TINYINT, "
                + "\"boxed\" TINYINT, "
                + "\"by\" TINYINT, "
                + "\"sh\" SMALLINT, "
                + "\"i\" INT, "
                + "\"l\" BIGINT, "
                + "\"f\" FLOAT, "
                + "\"d\" DOUBLE, "
                + "\"date\" DATETIME, "
                + "\"calendar\" DATETIME, "
                + "\"blob\" BLOB)", createSql(DdlTypes.class));
    }

    @Test
    public void constraintsArePlacedAfterTheColumnType() throws Exception {
        assertEquals("CREATE TABLE IF NOT EXISTS \"DdlConstraints\" ( "
                + "\"code\" TEXT PRIMARY KEY NOT NULL, "
                + "\"required\" TEXT NOT NULL, "
                + "\"email\" TEXT UNIQUE, "
                + "\"strict\" TEXT UNIQUE NOT NULL)", createSql(DdlConstraints.class));
    }

    @Test
    public void compositePrimaryKeyIsDeclaredOnceAtTheEnd() throws Exception {
        String sql = createSql(DdlComposite.class);
        assertEquals("CREATE TABLE IF NOT EXISTS \"DdlComposite\" ( "
                + "\"a\" INT NOT NULL, \"b\" TEXT NOT NULL, \"payload\" TEXT, "
                + "PRIMARY KEY(\"a\", \"b\"))", sql);
        assertFalse("columns of a composite key must not each carry PRIMARY KEY", sql.contains("INT PRIMARY KEY"));
    }

    @Test
    public void foreignKeysAreDeclaredAfterTheColumnsAndIndexed() throws Exception {
        FakeDatabaseModel db = register(DdlChild.class);
        db.getObjectModels().get(DdlChild.class).onCreateTable();

        assertEquals(2, driver.executed.size());
        assertEquals("CREATE TABLE IF NOT EXISTS \"DdlChild\" ( "
                + "\"id\" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, \"note\" TEXT, \"parentId\" BIGINT NOT NULL"
                + ", FOREIGN KEY(\"parentId\") REFERENCES \"DdlParent\"(\"id\"))", normalise(driver.executed.get(0)));
        assertEquals("CREATE INDEX IF NOT EXISTS IX_DdlChild_parentId ON \"DdlChild\" (\"parentId\");", normalise(driver.executed.get(1)));
    }

    @Test
    public void selfReferencingForeignKeyIsAddedWithAlterTable() throws Exception {
        FakeDatabaseModel db = register(DdlTree.class);
        db.getObjectModels().get(DdlTree.class).onCreateTable();

        assertEquals(3, driver.executed.size());
        assertEquals("the self reference cannot be part of CREATE TABLE",
                "CREATE TABLE IF NOT EXISTS \"DdlTree\" ( \"id\" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, \"label\" TEXT)",
                normalise(driver.executed.get(0)));
        assertEquals("ALTER TABLE \"DdlTree\" ADD COLUMN \"parentId\" BIGINT REFERENCES \"DdlTree\" (\"id\");", normalise(driver.executed.get(1)));
        assertEquals("CREATE INDEX IF NOT EXISTS IX_DdlTree_parentId ON \"DdlTree\" (\"parentId\");", normalise(driver.executed.get(2)));
    }

    @Test
    public void entityWithNoPersistableColumnsCannotCreateATable() throws Exception {
        FakeDatabaseModel db = register(DdlEmpty.class);
        try {
            db.getObjectModels().get(DdlEmpty.class).onCreateTable();
            fail("expected SQLException");
        } catch (SQLException e) {
            assertTrue(e.getMessage(), e.getMessage().startsWith("At least one column is required"));
        }
        assertTrue("nothing may be executed", driver.executed.isEmpty());
    }

    @Test
    public void rebuildRegeneratesTheFullStatement() throws Exception {
        FakeDatabaseModel db = register(DdlComposite.class);
        ObjectModel<?, ?, ?> model = db.getObjectModels().get(DdlComposite.class);
        model.onCreateTable();
        model.onCreateTable(true);
        assertEquals(2, driver.executed.size());
        assertEquals(normalise(driver.executed.get(0)), normalise(driver.executed.get(1)));
    }

    @Test
    public void onCreateTable_calledTwiceDoesNotFail() throws Exception {
        FakeDatabaseModel db = register(DdlComposite.class);
        ObjectModel<?, ?, ?> model = db.getObjectModels().get(DdlComposite.class);
        model.onCreateTable();
        model.onCreateTable();
    }

    @Test
    public void sqlFailureIsPropagatedToTheCaller() throws Exception {
        FakeDatabaseModel db = register(DdlComposite.class);
        driver.failOnSqlContaining = "CREATE TABLE";
        try {
            db.getObjectModels().get(DdlComposite.class).onCreateTable();
            fail("expected SQLException");
        } catch (SQLException e) {
            assertTrue(e.getMessage().contains("DdlComposite"));
        }
    }
}
